import type { Organization } from './organization-model';

export const ApplicationAccessKeyToLabel = {
  'Allowed': 'Allowed',
  'Blocked': 'Blocked'
} as const;
export type ApplicationAccessKey = keyof typeof ApplicationAccessKeyToLabel;

export const ApplicationComponentStateKeyToLabel = {
  'Published': 'Published',
  'Unpublished': 'Unpublished',
  'Deleted': 'Deleted',
  'DeletedUnpublished': 'Deleted Unpublished'
} as const;
export type ApplicationComponentStateKey = keyof typeof ApplicationComponentStateKeyToLabel;

export interface Application {
  /**
   * @displayName ApplicationId
   * @description Unique system identifier - GUID generated by system
   * @uiConstraints NEVER create input fields for this ID
   */
  id: string;
  /**
   * @displayName Name
   * @description Human-readable record identifier
   * @validationRule Required for create/update operations
   */
  name1: string;
  /**
   * @displayName Access
   * @validationRule Required for create/update operations
   */
  accessKey: ApplicationAccessKey;
  /**
   * @displayName CommonlyUsed
   */
  commonlyUsed?: boolean;
  /**
   * @displayName Component State
   * @validationRule Required for create/update operations
   */
  componentStateKey: ApplicationComponentStateKey;
  /**
   * @displayName Is Managed
   * @validationRule Required for create/update operations
   */
  isManaged: boolean;
  /**
   * @displayName Organization Id
   */
  organizationId?: Pick<Organization, 'id' | 'organizationName'>;
  /**
   * @displayName Record Overwrite Time
   * @validationRule Required for create/update operations
   */
  recordOverwriteTime: string;
  /**
   * @displayName Row id unique
   * @validationRule Required for create/update operations
   */
  rowIdUnique: string;
  /**
   * @displayName Solution
   * @validationRule Required for create/update operations
   */
  solution: string;
}

export const _Application = 'Application' as const;