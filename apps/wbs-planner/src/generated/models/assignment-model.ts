import type { Resource } from './resource-model';
import type { WBSItem } from './wbs-item-model';

export const AssignmentRoleOnTaskKeyToLabel = {
  'Lead': 'Lead',
  'Contributor': 'Contributor',
  'Reviewer': 'Reviewer',
  'Approver': 'Approver'
} as const;
export type AssignmentRoleOnTaskKey = keyof typeof AssignmentRoleOnTaskKeyToLabel;

export const AssignmentStatusKeyToLabel = {
  'NotStarted': 'Not Started',
  'InProgress': 'In Progress',
  'Completed': 'Completed',
  'Blocked': 'Blocked'
} as const;
export type AssignmentStatusKey = keyof typeof AssignmentStatusKeyToLabel;

export interface Assignment {
  /**
   * @displayName Assignment
   * @description Unique system identifier - GUID generated by system
   * @uiConstraints NEVER create input fields for this ID
   */
  id: string;
  /**
   * @displayName Assignment Name
   * @description Human-readable record identifier
   * @validationRule Required for create/update operations
   */
  assignmentName: string;
  /**
   * @displayName Allocation Percent
   * @validationRule Required for create/update operations
   */
  allocationPercent: number;
  /**
   * @displayName Assigned By
   * @validationRule Required for create/update operations
   */
  assignedBy: Pick<Resource, 'id' | 'resourceName'>;
  /**
   * @displayName Assigned Date
   * @validationRule Required for create/update operations
   */
  assignedDate: string;
  /**
   * @displayName Planned Finish Date
   * @validationRule Required for create/update operations
   */
  plannedFinishDate: string;
  /**
   * @displayName Planned Start Date
   * @validationRule Required for create/update operations
   */
  plannedStartDate: string;
  /**
   * @displayName Resource
   * @validationRule Required for create/update operations
   */
  resource: Pick<Resource, 'id' | 'resourceName'>;
  /**
   * @displayName Role On Task
   * @validationRule Required for create/update operations
   */
  roleOnTaskKey: AssignmentRoleOnTaskKey;
  /**
   * @displayName Status
   * @validationRule Required for create/update operations
   */
  statusKey: AssignmentStatusKey;
  /**
   * @displayName WBS Item
   * @validationRule Required for create/update operations
   */
  wBSItem: Pick<WBSItem, 'id' | 'wBSItemName'>;
}

export const _Assignment = 'Assignment' as const;