import type { Currency } from './currency-model';

export const ResourceResourceRoleKeyToLabel = {
  'ProjectManager': 'Project Manager',
  'DeliveryLead': 'Delivery Lead',
  'BusinessAnalyst': 'Business Analyst',
  'Developer': 'Developer',
  'Tester': 'Tester'
} as const;
export type ResourceResourceRoleKey = keyof typeof ResourceResourceRoleKeyToLabel;

export const ResourceStatusKeyToLabel = {
  'Active': 'Active',
  'Inactive': 'Inactive',
  'OnLeave': 'On Leave'
} as const;
export type ResourceStatusKey = keyof typeof ResourceStatusKeyToLabel;

export interface Resource {
  /**
   * @displayName Resource
   * @description Unique system identifier - GUID generated by system
   * @uiConstraints NEVER create input fields for this ID
   */
  id: string;
  /**
   * @displayName Resource Name
   * @description Human-readable record identifier
   * @validationRule Required for create/update operations
   */
  resourceName: string;
  /**
   * @displayName Cost Rate
   * @validationRule Required for create/update operations
   */
  costRate: number;
  /**
   * @displayName Cost Rate (Base)
   */
  costRateBase?: number;
  /**
   * @displayName Currency
   */
  currency?: Pick<Currency, 'id' | 'currencyName'>;
  /**
   * @displayName Email
   * @validationRule Required for create/update operations
   */
  email: string;
  /**
   * @displayName Exchange Rate
   */
  exchangeRate?: number;
  /**
   * @displayName Manager
   */
  manager?: Pick<Resource, 'id' | 'resourceName'>;
  /**
   * @displayName Phone
   */
  phone?: string;
  /**
   * @displayName Resource Role
   * @validationRule Required for create/update operations
   */
  resourceRoleKey: ResourceResourceRoleKey;
  /**
   * @displayName Status
   * @validationRule Required for create/update operations
   */
  statusKey: ResourceStatusKey;
  /**
   * @displayName Weekly Capacity Hours
   * @validationRule Required for create/update operations
   */
  weeklyCapacityHours: number;
}

export const _Resource = 'Resource' as const;