import type { Currency } from './currency-model';
import type { Resource } from './resource-model';
import type { Project } from './project-model';

export const WBSItemPriorityKeyToLabel = {
  'Low': 'Low',
  'Medium': 'Medium',
  'High': 'High',
  'Critical': 'Critical'
} as const;
export type WBSItemPriorityKey = keyof typeof WBSItemPriorityKeyToLabel;

export const WBSItemStatusKeyToLabel = {
  'NotStarted': 'Not Started',
  'InProgress': 'In Progress',
  'Completed': 'Completed',
  'Blocked': 'Blocked'
} as const;
export type WBSItemStatusKey = keyof typeof WBSItemStatusKeyToLabel;

export interface WBSItem {
  /**
   * @displayName WBS Item
   * @description Unique system identifier - GUID generated by system
   * @uiConstraints NEVER create input fields for this ID
   */
  id: string;
  /**
   * @displayName WBS Item Name
   * @description Human-readable record identifier
   * @validationRule Required for create/update operations
   */
  wBSItemName: string;
  /**
   * @displayName Baseline Cost
   * @validationRule Required for create/update operations
   */
  baselineCost: number;
  /**
   * @displayName Baseline Cost (Base)
   */
  baselineCostBase?: number;
  /**
   * @displayName Baseline Hours
   * @validationRule Required for create/update operations
   */
  baselineHours: number;
  /**
   * @displayName Currency
   */
  currency?: Pick<Currency, 'id' | 'currencyName'>;
  /**
   * @displayName Description
   */
  description?: string;
  /**
   * @displayName Exchange Rate
   */
  exchangeRate?: number;
  /**
   * @displayName Owner
   * @validationRule Required for create/update operations
   */
  owner: Pick<Resource, 'id' | 'resourceName'>;
  /**
   * @displayName Parent WBS Item
   */
  parentWBSItem?: Pick<WBSItem, 'id' | 'wBSItemName'>;
  /**
   * @displayName Planned Finish Date
   * @validationRule Required for create/update operations
   */
  plannedFinishDate: string;
  /**
   * @displayName Planned Start Date
   * @validationRule Required for create/update operations
   */
  plannedStartDate: string;
  /**
   * @displayName Priority
   * @validationRule Required for create/update operations
   */
  priorityKey: WBSItemPriorityKey;
  /**
   * @displayName Progress Percent
   * @validationRule Required for create/update operations
   */
  progressPercent: number;
  /**
   * @displayName Project
   * @validationRule Required for create/update operations
   */
  project: Pick<Project, 'id' | 'projectName'>;
  /**
   * @displayName Status
   * @validationRule Required for create/update operations
   */
  statusKey: WBSItemStatusKey;
  /**
   * @displayName WBS Code
   * @validationRule Required for create/update operations
   */
  wBSCode: string;
}

export const _WBSItem = 'WBSItem' as const;