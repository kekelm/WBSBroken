import type { Resource } from './resource-model';
import type { Currency } from './currency-model';
import type { Project } from './project-model';
import type { TimePeriod } from './time-period-model';
import type { WBSItem } from './wbs-item-model';

export const WBSEstimateEstimateStatusKeyToLabel = {
  'Draft': 'Draft',
  'Baselined': 'Baselined',
  'Revised': 'Revised',
  'Archived': 'Archived'
} as const;
export type WBSEstimateEstimateStatusKey = keyof typeof WBSEstimateEstimateStatusKeyToLabel;

export interface WBSEstimate {
  /**
   * @displayName WBS Estimate
   * @description Unique system identifier - GUID generated by system
   * @uiConstraints NEVER create input fields for this ID
   */
  id: string;
  /**
   * @displayName Estimate Name
   * @description Human-readable record identifier
   * @validationRule Required for create/update operations
   */
  estimateName: string;
  /**
   * @displayName Approval Comments
   */
  approvalComments?: string;
  /**
   * @displayName Approved By
   */
  approvedBy?: Pick<Resource, 'id' | 'resourceName'>;
  /**
   * @displayName Approved Date
   */
  approvedDate?: string;
  /**
   * @displayName Cost Rate
   * @validationRule Required for create/update operations
   */
  costRate: number;
  /**
   * @displayName Cost Rate (Base)
   */
  costRateBase?: number;
  /**
   * @displayName Created By
   * @validationRule Required for create/update operations
   */
  createdBy: Pick<Resource, 'id' | 'resourceName'>;
  /**
   * @displayName Created Date
   * @validationRule Required for create/update operations
   */
  createdDate: string;
  /**
   * @displayName Currency
   */
  currency?: Pick<Currency, 'id' | 'currencyName'>;
  /**
   * @displayName Estimate Status
   * @validationRule Required for create/update operations
   */
  estimateStatusKey: WBSEstimateEstimateStatusKey;
  /**
   * @displayName Exchange Rate
   */
  exchangeRate?: number;
  /**
   * @displayName Planned Cost
   * @validationRule Required for create/update operations
   */
  plannedCost: number;
  /**
   * @displayName Planned Cost (Base)
   */
  plannedCostBase?: number;
  /**
   * @displayName Planned Hours
   * @validationRule Required for create/update operations
   */
  plannedHours: number;
  /**
   * @displayName Project
   * @validationRule Required for create/update operations
   */
  project: Pick<Project, 'id' | 'projectName'>;
  /**
   * @displayName Resource
   * @validationRule Required for create/update operations
   */
  resource: Pick<Resource, 'id' | 'resourceName'>;
  /**
   * @displayName Time Period
   * @validationRule Required for create/update operations
   */
  timePeriod: Pick<TimePeriod, 'id' | 'timePeriodName'>;
  /**
   * @displayName WBS Item
   * @validationRule Required for create/update operations
   */
  wBSItem: Pick<WBSItem, 'id' | 'wBSItemName'>;
}

export const _WBSEstimate = 'WBSEstimate' as const;