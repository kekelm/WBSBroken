import type { Currency } from './currency-model';
import type { Project } from './project-model';
import type { Resource } from './resource-model';
import type { TimePeriod } from './time-period-model';
import type { WBSItem } from './wbs-item-model';

export const ResourceHourEntryEntryStatusKeyToLabel = {
  'Draft': 'Draft',
  'Submitted': 'Submitted',
  'Approved': 'Approved',
  'Rejected': 'Rejected'
} as const;
export type ResourceHourEntryEntryStatusKey = keyof typeof ResourceHourEntryEntryStatusKeyToLabel;

export interface ResourceHourEntry {
  /**
   * @displayName Resource Hour Entry
   * @description Unique system identifier - GUID generated by system
   * @uiConstraints NEVER create input fields for this ID
   */
  id: string;
  /**
   * @displayName Entry Name
   * @description Human-readable record identifier
   * @validationRule Required for create/update operations
   */
  entryName: string;
  /**
   * @displayName Actual Cost
   * @validationRule Required for create/update operations
   */
  actualCost: number;
  /**
   * @displayName Actual Cost (Base)
   */
  actualCostBase?: number;
  /**
   * @displayName Actual Hours
   * @validationRule Required for create/update operations
   */
  actualHours: number;
  /**
   * @displayName Currency
   */
  currency?: Pick<Currency, 'id' | 'currencyName'>;
  /**
   * @displayName Entry Status
   * @validationRule Required for create/update operations
   */
  entryStatusKey: ResourceHourEntryEntryStatusKey;
  /**
   * @displayName Exchange Rate
   */
  exchangeRate?: number;
  /**
   * @displayName Project
   * @validationRule Required for create/update operations
   */
  project: Pick<Project, 'id' | 'projectName'>;
  /**
   * @displayName Resource
   * @validationRule Required for create/update operations
   */
  resource: Pick<Resource, 'id' | 'resourceName'>;
  /**
   * @displayName Review Comments
   */
  reviewComments?: string;
  /**
   * @displayName Reviewed By
   */
  reviewedBy?: Pick<Resource, 'id' | 'resourceName'>;
  /**
   * @displayName Reviewed Date
   */
  reviewedDate?: string;
  /**
   * @displayName Submitted Date
   */
  submittedDate?: string;
  /**
   * @displayName Time Period
   * @validationRule Required for create/update operations
   */
  timePeriod: Pick<TimePeriod, 'id' | 'timePeriodName'>;
  /**
   * @displayName WBS Item
   * @validationRule Required for create/update operations
   */
  wBSItem: Pick<WBSItem, 'id' | 'wBSItemName'>;
}

export const _ResourceHourEntry = 'ResourceHourEntry' as const;