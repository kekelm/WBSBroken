import type { Resource } from './resource-model';
import type { Project } from './project-model';
import type { WBSItem } from './wbs-item-model';

export const CommentCommentTypeKeyToLabel = {
  'General': 'General',
  'StatusUpdate': 'Status Update',
  'RiskNote': 'Risk Note',
  'Decision': 'Decision',
  'Issue': 'Issue'
} as const;
export type CommentCommentTypeKey = keyof typeof CommentCommentTypeKeyToLabel;

export const CommentVisibilityKeyToLabel = {
  'ProjectTeam': 'Project Team',
  'ManagersOnly': 'Managers Only',
  'Stakeholders': 'Stakeholders'
} as const;
export type CommentVisibilityKey = keyof typeof CommentVisibilityKeyToLabel;

export interface Comment {
  /**
   * @displayName Comment
   * @description Unique system identifier - GUID generated by system
   * @uiConstraints NEVER create input fields for this ID
   */
  id: string;
  /**
   * @displayName Comment Name
   * @description Human-readable record identifier
   * @validationRule Required for create/update operations
   */
  commentName: string;
  /**
   * @displayName Author
   * @validationRule Required for create/update operations
   */
  author: Pick<Resource, 'id' | 'resourceName'>;
  /**
   * @displayName Comment Text
   * @validationRule Required for create/update operations
   */
  commentText: string;
  /**
   * @displayName Comment Type
   * @validationRule Required for create/update operations
   */
  commentTypeKey: CommentCommentTypeKey;
  /**
   * @displayName Created Date
   * @validationRule Required for create/update operations
   */
  createdDate: string;
  /**
   * @displayName Project
   * @validationRule Required for create/update operations
   */
  project: Pick<Project, 'id' | 'projectName'>;
  /**
   * @displayName Visibility
   * @validationRule Required for create/update operations
   */
  visibilityKey: CommentVisibilityKey;
  /**
   * @displayName WBS Item
   */
  wBSItem?: Pick<WBSItem, 'id' | 'wBSItemName'>;
}

export const _Comment = 'Comment' as const;