import type { WBSItem } from './wbs-item-model';
import type { Project } from './project-model';

export const WBSDependencyDependencyTypeKeyToLabel = {
  'FinishToStart': 'Finish-to-Start',
  'StartToStart': 'Start-to-Start',
  'FinishToFinish': 'Finish-to-Finish',
  'StartToFinish': 'Start-to-Finish'
} as const;
export type WBSDependencyDependencyTypeKey = keyof typeof WBSDependencyDependencyTypeKeyToLabel;

export const WBSDependencyStatusKeyToLabel = {
  'Proposed': 'Proposed',
  'Active': 'Active',
  'Resolved': 'Resolved',
  'Cancelled': 'Cancelled'
} as const;
export type WBSDependencyStatusKey = keyof typeof WBSDependencyStatusKeyToLabel;

export interface WBSDependency {
  /**
   * @displayName WBS Dependency
   * @description Unique system identifier - GUID generated by system
   * @uiConstraints NEVER create input fields for this ID
   */
  id: string;
  /**
   * @displayName Dependency Name
   * @description Human-readable record identifier
   * @validationRule Required for create/update operations
   */
  dependencyName: string;
  /**
   * @displayName Dependency Type
   * @validationRule Required for create/update operations
   */
  dependencyTypeKey: WBSDependencyDependencyTypeKey;
  /**
   * @displayName Lag Days
   * @validationRule Required for create/update operations
   */
  lagDays: number;
  /**
   * @displayName Notes
   */
  notes?: string;
  /**
   * @displayName Predecessor WBS Item
   * @validationRule Required for create/update operations
   */
  predecessorWBSItem: Pick<WBSItem, 'id' | 'wBSItemName'>;
  /**
   * @displayName Project
   * @validationRule Required for create/update operations
   */
  project: Pick<Project, 'id' | 'projectName'>;
  /**
   * @displayName Status
   * @validationRule Required for create/update operations
   */
  statusKey: WBSDependencyStatusKey;
  /**
   * @displayName Successor WBS Item
   * @validationRule Required for create/update operations
   */
  successorWBSItem: Pick<WBSItem, 'id' | 'wBSItemName'>;
}

export const _WBSDependency = 'WBSDependency' as const;